import { z, nullableResponseTimestamp, responseTimestamp } from "../../openapi";
import { CODE_JOB_STATUSES } from "./lifecycle";
import type { schema } from "../../database";

export const jobResponse = z.object({
  id: z.string(),
  runId: z.string(),
  taskId: z.string().nullable(),
  integrationId: z.string().nullable(),
  status: z.enum(CODE_JOB_STATUSES),
  outcome: z.enum(["pr_opened", "no_changes"]).nullable(),
  backend: z.literal("repo-ci"),
  phase: z.string().nullable(),
  progress: z.string().nullable(),
  repositoryOwner: z.string(),
  repositoryName: z.string(),
  baseRef: z.string().nullable(),
  baseSha: z.string().nullable(),
  branch: z.string(),
  model: z.string(),
  externalUrl: z.string().nullable(),
  prNumber: z.number().nullable(),
  prUrl: z.string().nullable(),
  commitSha: z.string().nullable(),
  summary: z.string().nullable(),
  error: z.string().nullable(),
  createdAt: responseTimestamp,
  startedAt: nullableResponseTimestamp,
  finishedAt: nullableResponseTimestamp,
  deadline: responseTimestamp,
});

// Explicit allowlist: callback credential hashes, leases, and changeset bytes
// never belong in a response, including responses to the owner.
export function publicJob(job: typeof schema.agentJobTable.$inferSelect) {
  const {
    id,
    runId,
    taskId,
    integrationId,
    status,
    outcome,
    backend,
    phase,
    progress,
    repositoryOwner,
    repositoryName,
    baseRef,
    baseSha,
    branch,
    model,
    externalUrl,
    prNumber,
    prUrl,
    commitSha,
    summary,
    error,
    createdAt,
    startedAt,
    finishedAt,
    deadline,
  } = job;
  return {
    id,
    runId,
    taskId,
    integrationId,
    status,
    outcome,
    backend,
    phase,
    progress,
    repositoryOwner,
    repositoryName,
    baseRef,
    baseSha,
    branch,
    model,
    externalUrl,
    prNumber,
    prUrl,
    commitSha,
    summary,
    error,
    createdAt,
    startedAt,
    finishedAt,
    deadline,
  };
}
